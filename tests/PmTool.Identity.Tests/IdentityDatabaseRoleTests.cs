    [Test]
    public async Task RuntimeRole_AfterMigration_CanDoEverythingTheModuleDoes()
    {
        // Arrange：遷移用擁有者，之後所有服務都用執行的角色連線；金鑰也存在同一個 schema（有序列的資料表）。
        var (host, _, _) = await StartWithRuntimeRoleAsync(
            services => services.AddDataProtection().SetApplicationName("pm-tool-tests").PersistKeysToIdentityModule());
        await using var _ = host;

        // Act：建立第一個擁有者、登入、新增人員、改密碼、停用、重設密碼、登出，再存一把金鑰。
        var owner = await host.StartWithOwnerAsync();
        var actor = new Actor(owner.OrganizationId, owner.PersonId, IsOrganizationAdmin: true);
        var member = await host.AddUserAsync(actor);
        var session = await host.StartSessionAsync(member);
        var changed = await host.Accounts.ChangeOwnPasswordAsync(session.Token, TestData.Password, "example-password-2", false, CancellationToken.None);
        var disabled = await host.People.SetDisabledAsync(actor, member.PersonId, true, CancellationToken.None);
        var enabled = await host.People.SetDisabledAsync(actor, member.PersonId, false, CancellationToken.None);
        var reset = await host.People.ResetPasswordAsync(actor, member.PersonId, "example-password-3", CancellationToken.None);
        var ownerSession = await host.StartSessionAsync(owner);
        await host.Sessions.EndAsync(ownerSession.Token, CancellationToken.None);
        var protectedPayload = host.Services.GetRequiredService<IDataProtectionProvider>().CreateProtector("tests").Protect("範例");

        // Assert
        using (Assert.EnterMultipleScope())
        {
            Assert.That((changed.Succeeded, disabled.Succeeded, enabled.Succeeded, reset.Succeeded), Is.EqualTo((true, true, true, true)));
            Assert.That(await host.Sessions.FindAsync(ownerSession.Token, CancellationToken.None), Is.Null);
            Assert.That(await host.Authentication.SignInAsync(member.Email, "example-password-3", CancellationToken.None), Is.Not.Null);
            Assert.That(protectedPayload, Is.Not.Empty);
        }
    }

