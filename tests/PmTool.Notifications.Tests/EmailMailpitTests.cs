using System.Text.Json;
using DotNet.Testcontainers.Builders;
using DotNet.Testcontainers.Containers;
using Microsoft.EntityFrameworkCore;
using PmTool.Notifications.Email;
using PmTool.Notifications.Persistence;

namespace PmTool.Notifications.Tests;

/// <summary>
/// 整合測試：開一個 Mailpit（收信用的測試 SMTP 主機，不加密、不登入），用真的 MailKit 寄一封，
/// 確認寄得出去、主旨、標頭與跳脫都對。這是唯一一個真的連 SMTP 的測試。
/// </summary>
[TestFixture]
public sealed class EmailMailpitTests
{
    private const int SmtpPort = 1025;
    private const int ApiPort = 8025;

    private IContainer? _mailpit;
    private HttpClient? _api;

    private IContainer Mailpit => _mailpit ?? throw new InvalidOperationException("Mailpit 還沒啟動。");

    private int MappedSmtpPort => Mailpit.GetMappedPublicPort(SmtpPort);

    [OneTimeSetUp]
    public async Task StartMailpitAsync()
    {
        _mailpit = new ContainerBuilder("axllent/mailpit:v1.29")
            .WithPortBinding(SmtpPort, true)
            .WithPortBinding(ApiPort, true)
            .WithWaitStrategy(Wait.ForUnixContainer().UntilHttpRequestIsSucceeded(request => request.ForPort(ApiPort).ForPath("/api/v1/info")))
            .Build();
        await _mailpit.StartAsync();
        _api = new HttpClient { BaseAddress = new Uri($"http://{_mailpit.Hostname}:{_mailpit.GetMappedPublicPort(ApiPort)}") };
    }

    [OneTimeTearDown]
    public async Task StopMailpitAsync()
    {
        _api?.Dispose();
        if (_mailpit is not null)
        {
            await _mailpit.DisposeAsync();
        }
    }

    private async Task<JsonElement> GetJsonAsync(string path)
    {
        using var response = await _api!.GetAsync(path);
        response.EnsureSuccessStatusCode();
        return JsonDocument.Parse(await response.Content.ReadAsStringAsync()).RootElement.Clone();
    }

    /// <summary>等信到 Mailpit（SMTP 收下之後存起來很快，但不是同步的）。</summary>
    private async Task<JsonElement> WaitForMessageAsync(string recipient)
    {
        for (var attempt = 0; attempt < 50; attempt++)
        {
            var list = await GetJsonAsync($"/api/v1/search?query={Uri.EscapeDataString($"to:{recipient}")}");
            if (list.GetProperty("messages").GetArrayLength() > 0)
            {
                return list.GetProperty("messages")[0];
            }

            await Task.Delay(100);
        }

        throw new TimeoutException($"Mailpit 一直沒收到寄給 {recipient} 的信。");
    }

    [Test]
    public async Task Dispatch_RealMailKitTransport_DeliversAnAutoGeneratedMailWithEscapedHtml()
    {
        // Arrange：連接埠是容器隨機對應的，不在設定允許的清單裡，所以直接寫進資料表。
        var clock = new ManualClock();
        var organization = Guid.CreateVersion7();
        var item = new EventBuilder(organization, Guid.CreateVersion7(), Guid.CreateVersion7());
        Guid me = Guid.CreateVersion7(), other = Guid.CreateVersion7();
        var recipient = $"me-{me:N}@example.com";
        await using var host = await NotificationsTestHost.StartAsync(
            new PmTool.Abstractions.DatabaseConnections(await PostgresServer.CreateDatabaseAsync()), null, clock, null, useRealEmailTransport: true);
        host.Access.Allow(item.ProjectId, me, other);
        host.People.Add(organization, me, "Me <Example>", recipient);
        host.People.Add(organization, other, "Other & Co", $"other-{other:N}@example.com");
        await using (var db = await host.CreateDbContextAsync())
        {
            db.EmailSettings.Add(new EmailSettingsRow
            {
                OrganizationId = organization,
                Enabled = true,
                Provider = EmailProvider.Smtp,
                Host = Mailpit.Hostname,
                Port = MappedSmtpPort,
                Security = SmtpSecurity.None,
                FromAddress = "noreply@example.com",
                FromName = "Example 公司",
                SiteUrl = "https://pm.example.com",
                UpdatedAt = clock.GetUtcNow(),
                UpdatedBy = other,
                ConsecutiveFailures = 0,
            });
            await db.SaveChangesAsync();
        }

        await host.Consumer.HandleAsync(
            [item.Created(other, assignee: me) with { OccurredAt = clock.GetUtcNow() },
             item.Commented(other, "<b>bold</b> & \"more\"") with { OccurredAt = clock.GetUtcNow() }],
            CancellationToken.None);
        clock.Advance(EmailRules.Delay + TimeSpan.FromSeconds(1));

        // Act
        var sent = await host.Dispatcher.DispatchAsync(CancellationToken.None);
        var summary = await WaitForMessageAsync(recipient);
        var id = summary.GetProperty("ID").GetString();
        var message = await GetJsonAsync($"/api/v1/message/{id}");
        var headers = await GetJsonAsync($"/api/v1/message/{id}/headers");

        // Assert
        using (Assert.EnterMultipleScope())
        {
            Assert.That(sent, Is.EqualTo(1));
            Assert.That(summary.GetProperty("Subject").GetString(), Is.EqualTo("2 則新通知：WEB-1 範例項目"));
            Assert.That(message.GetProperty("From").GetProperty("Address").GetString(), Is.EqualTo("noreply@example.com"));
            Assert.That(message.GetProperty("From").GetProperty("Name").GetString(), Is.EqualTo("Example 公司"));
            Assert.That(headers.GetProperty("Auto-Submitted")[0].GetString(), Is.EqualTo("auto-generated"));
            Assert.That(headers.GetProperty("X-Auto-Response-Suppress")[0].GetString(), Is.EqualTo("All"));
            Assert.That(message.GetProperty("HTML").GetString(), Does.Contain("&lt;b&gt;bold&lt;/b&gt;").And.Not.Contain("<b>bold</b>"));
            Assert.That(message.GetProperty("HTML").GetString(), Does.Contain("Other &amp; Co"));
            Assert.That(message.GetProperty("Text").GetString(), Does.Contain("<b>bold</b> & \"more\""));
            Assert.That(message.GetProperty("Text").GetString(), Does.Contain("https://pm.example.com/projects/WEB/items/WEB-1"));
        }
    }

    [Test]
    public void OpenAsync_NothingListening_ThrowsUnreachable()
    {
        // Arrange
        var transport = new MailKitEmailTransport();

        // Act
        var failure = Assert.ThrowsAsync<EmailDeliveryException>(async () =>
            await transport.OpenAsync(new SmtpConnection("127.0.0.1", 1, SmtpSecurity.None, null, null), CancellationToken.None));

        // Assert
        Assert.That(failure!.Kind, Is.EqualTo(EmailFailureKind.Unreachable));
    }

    [Test]
    public void OpenAsync_StartTlsAgainstAServerWithoutIt_FailsInsteadOfFallingBackToPlainText()
    {
        // Arrange
        var transport = new MailKitEmailTransport();

        // Act
        var failure = Assert.ThrowsAsync<EmailDeliveryException>(async () =>
            await transport.OpenAsync(new SmtpConnection(Mailpit.Hostname, MappedSmtpPort, SmtpSecurity.StartTls, null, null), CancellationToken.None));

        // Assert
        Assert.That(failure!.Kind, Is.EqualTo(EmailFailureKind.TlsFailed));
    }

    [Test]
    public async Task SendAsync_ThroughOneSession_DeliversSeveralMails()
    {
        // Arrange
        var transport = new MailKitEmailTransport();
        var first = $"a-{Guid.NewGuid():N}@example.com";
        var second = $"b-{Guid.NewGuid():N}@example.com";

        // Act
        await using (var session = await transport.OpenAsync(
            new SmtpConnection(Mailpit.Hostname, MappedSmtpPort, SmtpSecurity.None, null, null), CancellationToken.None))
        {
            await session.SendAsync(EmailComposer.Test("noreply@example.com", null, first, null), CancellationToken.None);
            await session.SendAsync(EmailComposer.Test("noreply@example.com", null, second, null), CancellationToken.None);
        }

        // Assert
        using (Assert.EnterMultipleScope())
        {
            Assert.That((await WaitForMessageAsync(first)).GetProperty("Subject").GetString(), Is.EqualTo(EmailComposer.TestSubject));
            Assert.That((await WaitForMessageAsync(second)).GetProperty("Subject").GetString(), Is.EqualTo(EmailComposer.TestSubject));
        }
    }
}
